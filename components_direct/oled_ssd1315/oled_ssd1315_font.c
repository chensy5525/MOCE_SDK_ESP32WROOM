bool oled_ssd1315_font_ascii(char ch, uint8_t columns[5])
{
    if (columns == NULL) return false;
    if (ch >= 'a' && ch <= 'z') ch = (char)(ch - ('a' - 'A'));
    for (size_t i = 0; i < sizeof(k_ascii) / sizeof(k_ascii[0]); ++i) {
        if (k_ascii[i].ch == ch) {
            memcpy(columns, k_ascii[i].columns, 5U);
            return true;
        }
    }
    memset(columns, 0, 5U);
    return false;
}

bool oled_ssd1315_font_chinese(const char *utf8, size_t len, uint16_t rows[16])
{
    if (utf8 == NULL || rows == NULL || len != 3U) return false;
    for (size_t i = 0; i < sizeof(k_chinese) / sizeof(k_chinese[0]); ++i) {
        if (memcmp(utf8, k_chinese[i].utf8, 3U) == 0) {
            memcpy(rows, k_chinese[i].rows, sizeof(k_chinese[i].rows));
            return true;
        }
    }
    memset(rows, 0, sizeof(uint16_t) * 16U);
    return false;
}
